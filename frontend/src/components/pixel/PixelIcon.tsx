interface PixelIconProps {
  name: IconName;
  size?: number;
  className?: string;
  style?: React.CSSProperties;
}

export function PixelIcon({ name, size = 3, className, style: extraStyle }: PixelIconProps) {
  const grid = ICONS[name];
  return (
    <div className={className} style={{ imageRendering: "pixelated", lineHeight: 0, ...extraStyle }}>
      {grid.map((row, y) => (
        <div key={y} style={{ display: "flex", height: size }}>
          {row.map((color, x) => (
            <div
              key={x}
              style={{
                width: size,
                height: size,
                backgroundColor: color,
              }}
            />
          ))}
        </div>
      ))}
    </div>
  );
}

